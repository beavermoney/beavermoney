-- Merchants are optional expense metadata. Existing transactions remain unassigned.
CREATE TABLE merchants (
 id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 90194313216) PRIMARY KEY,
 create_time timestamptz NOT NULL,
 update_time timestamptz NOT NULL,
 name varchar(120) NOT NULL,
 name_key varchar(512) NOT NULL,
 icon varchar(253) NULL,
 household_id bigint NOT NULL,
 CONSTRAINT merchants_households_merchants FOREIGN KEY (household_id) REFERENCES households(id)
);
CREATE UNIQUE INDEX merchant_household_id_name_key ON merchants(household_id,name_key);
ALTER TABLE transactions ADD COLUMN merchant_id bigint NULL;
ALTER TABLE transactions ADD CONSTRAINT transactions_merchants_transactions FOREIGN KEY (merchant_id) REFERENCES merchants(id) ON DELETE RESTRICT;
CREATE INDEX transaction_household_id_merchant_id_datetime ON transactions(household_id,merchant_id,datetime);

-- Defense in depth for direct writes: references cannot cross households and
-- a merchant may only be attached to expense categories. Reassignment and hard
-- deletion during a merge are performed together by the GraphQL transaction.
CREATE FUNCTION validate_transaction_merchant() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.merchant_id IS NOT NULL THEN
  PERFORM 1 FROM transaction_categories WHERE id=NEW.category_id FOR SHARE;
  IF NOT EXISTS (SELECT 1 FROM merchants WHERE id=NEW.merchant_id AND household_id=NEW.household_id) THEN
   RAISE EXCEPTION 'merchant must belong to the transaction household';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM transaction_categories WHERE id=NEW.category_id AND household_id=NEW.household_id AND type='expense') THEN
   RAISE EXCEPTION 'only expenses can have a merchant';
  END IF;
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER transactions_merchant_guard BEFORE INSERT OR UPDATE OF merchant_id,category_id,household_id ON transactions FOR EACH ROW EXECUTE FUNCTION validate_transaction_merchant();

CREATE FUNCTION protect_merchant_household() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.household_id IS DISTINCT FROM OLD.household_id THEN
  RAISE EXCEPTION 'merchant household is immutable';
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER merchants_household_guard BEFORE UPDATE OF household_id ON merchants FOR EACH ROW EXECUTE FUNCTION protect_merchant_household();

-- Category type is hidden from the update API. Preserve the same invariant for
-- maintenance SQL, including concurrent expense assignment and category edits.
CREATE FUNCTION protect_merchant_category() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.type,NEW.household_id) IS DISTINCT FROM (OLD.type,OLD.household_id)
    AND EXISTS (SELECT 1 FROM transactions WHERE category_id=OLD.id AND merchant_id IS NOT NULL) THEN
  RAISE EXCEPTION 'a merchant expense category cannot change type or household';
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER transaction_categories_merchant_guard BEFORE UPDATE OF type,household_id ON transaction_categories FOR EACH ROW EXECUTE FUNCTION protect_merchant_category();
