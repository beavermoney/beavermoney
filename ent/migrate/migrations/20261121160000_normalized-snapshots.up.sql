-- Shared, immutable observations. They deliberately do not cascade from a
-- journal entry: later snapshots can reuse a version first recorded earlier.
CREATE TABLE snapshot_accounts (
 id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 81604378624) PRIMARY KEY,
 household_id bigint NOT NULL REFERENCES households(id) ON DELETE CASCADE,
 account_id bigint NOT NULL REFERENCES accounts(id),
 observed_at timestamptz NOT NULL,
 revision bigint NOT NULL,
 balance numeric(36,18) NOT NULL,
 archived boolean NOT NULL,
 CONSTRAINT snapshot_account_archived_empty CHECK (NOT archived OR balance=0)
);
CREATE UNIQUE INDEX snapshotaccount_household_id_account_id_observed_at_revision
 ON snapshot_accounts(household_id,account_id,observed_at DESC,revision DESC);
CREATE TABLE snapshot_investments (
 id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 85899345920) PRIMARY KEY,
 household_id bigint NOT NULL REFERENCES households(id) ON DELETE CASCADE,
 investment_id bigint NOT NULL REFERENCES investments(id),
 observed_at timestamptz NOT NULL,
 revision bigint NOT NULL,
 quantity numeric(36,18) NOT NULL,
 average_cost numeric(36,18),
 market_price numeric(36,18) NOT NULL,
 average_confirmed_at timestamptz,
 needs_review boolean NOT NULL,
 archived boolean NOT NULL,
 CONSTRAINT snapshot_investment_average_nonnegative CHECK (average_cost IS NULL OR average_cost>=0),
 CONSTRAINT snapshot_investment_archived_empty CHECK (NOT archived OR quantity=0)
);
CREATE UNIQUE INDEX snapshotinvestment_household_id_investment_id_observed_at_revision
 ON snapshot_investments(household_id,investment_id,observed_at DESC,revision DESC);
ALTER TABLE snapshots ADD COLUMN format_version bigint NOT NULL DEFAULT 0;
ALTER TABLE snapshot_rates ADD COLUMN as_of timestamptz;
ALTER TABLE investments ADD COLUMN archived boolean NOT NULL DEFAULT false;
ALTER TABLE investments ADD CONSTRAINT archived_investment_empty CHECK (NOT archived OR amount=0);
-- Older versions permitted offsetting cash/shares to archive with a zero net
-- value. Restore those nonempty accounts rather than discard their balances.
UPDATE accounts SET archived=false WHERE archived AND
 (balance<>0 OR value<>0 OR EXISTS(SELECT 1 FROM investments i WHERE i.account_id=accounts.id AND i.amount<>0));
ALTER TABLE investments DROP CONSTRAINT confirmed_average_cost_nonnegative;
ALTER TABLE investments ALTER COLUMN confirmed_average_cost TYPE numeric(36,18) USING confirmed_average_cost::numeric;
ALTER TABLE investments ADD CONSTRAINT manual_average_nonnegative CHECK (confirmed_average_cost IS NULL OR confirmed_average_cost>=0);
ALTER TABLE accounts ADD CONSTRAINT archived_account_empty CHECK (NOT archived OR (balance=0 AND value=0));

-- Convert any local/prototype JSON captures before removing that column. Legacy
-- category-only snapshots remain untouched and have format_version=0.
CREATE TEMP TABLE captured_accounts ON COMMIT DROP AS
 SELECT s.id AS revision,s.household_id,s.create_time AS observed_at,
 (a->>'id')::bigint AS account_id,(a->>'cash')::numeric AS balance,false AS archived
 FROM snapshots s CROSS JOIN LATERAL jsonb_array_elements(s.review_data::jsonb->'accounts') a
 WHERE s.review_data IS NOT NULL;
-- A complete capture omitting a previously seen account records its archival.
INSERT INTO captured_accounts
 SELECT s.id,s.household_id,s.create_time,prior.account_id,0,true
 FROM snapshots s JOIN (SELECT DISTINCT household_id,account_id FROM captured_accounts) prior ON prior.household_id=s.household_id
 WHERE s.review_data IS NOT NULL AND (s.review_data::jsonb->>'complete')::boolean IS TRUE
 AND EXISTS(SELECT 1 FROM captured_accounts a WHERE a.account_id=prior.account_id AND (a.observed_at,a.revision)<(s.create_time,s.id))
 AND NOT EXISTS(SELECT 1 FROM captured_accounts a WHERE a.account_id=prior.account_id AND a.revision=s.id);
INSERT INTO snapshot_accounts (household_id,account_id,observed_at,revision,balance,archived)
 SELECT household_id,account_id,observed_at,revision,balance,archived FROM (
  SELECT *,lag(ROW(balance,archived)) OVER(PARTITION BY household_id,account_id ORDER BY observed_at,revision) AS previous
  FROM captured_accounts
 ) a WHERE previous IS DISTINCT FROM ROW(balance,archived);
CREATE TEMP TABLE captured_investments ON COMMIT DROP AS
 SELECT s.id AS revision,s.household_id,s.create_time AS observed_at,
 (h->>'id')::bigint AS investment_id,(h->>'quantity')::numeric AS quantity,
 (h->>'average')::numeric AS average_cost,(h->>'price')::numeric AS market_price,
 (h->>'confirmedAt')::timestamptz AS average_confirmed_at,(h->>'needsReview')::boolean AS needs_review,false AS archived
 FROM snapshots s CROSS JOIN LATERAL jsonb_array_elements(s.review_data::jsonb->'accounts') a
 CROSS JOIN LATERAL jsonb_array_elements(a->'holdings') h WHERE s.review_data IS NOT NULL;
INSERT INTO captured_investments
 SELECT s.id,s.household_id,s.create_time,prior.investment_id,0,prior.average_cost,prior.market_price,prior.average_confirmed_at,false,true
 FROM snapshots s CROSS JOIN LATERAL (
  SELECT DISTINCT ON(investment_id) * FROM captured_investments i
  WHERE i.household_id=s.household_id AND (i.observed_at,i.revision)<(s.create_time,s.id)
  ORDER BY investment_id,observed_at DESC,revision DESC
 ) prior
 WHERE s.review_data IS NOT NULL AND (s.review_data::jsonb->>'complete')::boolean IS TRUE
 AND NOT EXISTS(SELECT 1 FROM captured_investments i WHERE i.investment_id=prior.investment_id AND i.revision=s.id);
INSERT INTO snapshot_investments (household_id,investment_id,observed_at,revision,quantity,average_cost,market_price,average_confirmed_at,needs_review,archived)
 SELECT household_id,investment_id,observed_at,revision,quantity,average_cost,market_price,average_confirmed_at,needs_review,archived FROM (
 SELECT *,lag(ROW(quantity,average_cost,market_price,average_confirmed_at,needs_review,archived)) OVER(PARTITION BY household_id,investment_id ORDER BY observed_at,revision) AS previous
 FROM captured_investments
 ) i WHERE previous IS DISTINCT FROM ROW(quantity,average_cost,market_price,average_confirmed_at,needs_review,archived);
UPDATE snapshot_rates r SET as_of=(fx->>'asOf')::timestamptz
 FROM snapshots s CROSS JOIN LATERAL jsonb_array_elements(s.review_data::jsonb->'rates') fx,
 household_currencies f,household_currencies t
 WHERE r.snapshot_id=s.id AND f.id=r.from_household_currency_id AND t.id=r.to_household_currency_id
 AND fx->>'from'=f.code AND fx->>'to'=t.code;
UPDATE snapshots SET format_version=1 WHERE review_data IS NOT NULL;
ALTER TABLE snapshots DROP COLUMN review_data;

-- Immutable identity/classification keeps historical joins reliable.
CREATE FUNCTION enforce_account_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.user_id,NEW.category,NEW.type,NEW.household_currency_id,NEW.household_id) IS DISTINCT FROM
    (OLD.user_id,OLD.category,OLD.type,OLD.household_currency_id,OLD.household_id) THEN
  RAISE EXCEPTION 'Account owner, category, type and currency are immutable';
 END IF;
 IF NEW.archived AND EXISTS(SELECT 1 FROM investments WHERE account_id=NEW.id AND amount<>0) THEN
  RAISE EXCEPTION 'An account with shares cannot be archived';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER account_identity_guard BEFORE UPDATE ON accounts FOR EACH ROW EXECUTE FUNCTION enforce_account_identity();
CREATE FUNCTION enforce_investment_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.account_id,NEW.household_currency_id,NEW.household_id,NEW.user_id,NEW.symbol,NEW.type) IS DISTINCT FROM
    (OLD.account_id,OLD.household_currency_id,OLD.household_id,OLD.user_id,OLD.symbol,OLD.type) THEN
  RAISE EXCEPTION 'Investment account, owner, symbol, type and currency are immutable';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER investment_identity_guard BEFORE UPDATE ON investments FOR EACH ROW EXECUTE FUNCTION enforce_investment_identity();

-- Financial observations are append-only. Journal notes are the only editable
-- part of a capture; deletion remains available without rewriting later values.
CREATE FUNCTION reject_snapshot_value_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'Saved snapshot values are immutable';
END $$;
CREATE TRIGGER snapshot_account_immutable BEFORE UPDATE ON snapshot_accounts FOR EACH ROW EXECUTE FUNCTION reject_snapshot_value_update();
CREATE TRIGGER snapshot_investment_immutable BEFORE UPDATE ON snapshot_investments FOR EACH ROW EXECUTE FUNCTION reject_snapshot_value_update();
CREATE TRIGGER snapshot_rate_immutable BEFORE UPDATE ON snapshot_rates FOR EACH ROW EXECUTE FUNCTION reject_snapshot_value_update();
CREATE TRIGGER snapshot_entry_immutable BEFORE UPDATE ON snapshot_entries FOR EACH ROW EXECUTE FUNCTION reject_snapshot_value_update();
CREATE FUNCTION enforce_snapshot_stamp() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.create_time,NEW.household_id,NEW.format_version) IS DISTINCT FROM
    (OLD.create_time,OLD.household_id,OLD.format_version) THEN
  RAISE EXCEPTION 'Snapshot capture time and format are immutable';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER snapshot_stamp_immutable BEFORE UPDATE ON snapshots FOR EACH ROW EXECUTE FUNCTION enforce_snapshot_stamp();
